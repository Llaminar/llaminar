#!/usr/bin/env python3
"""Golden outputs of a small synthetic DeepSeek-V4 vision tower (reference = official math).

Weights are generated by the integer hash shared with Test__DeepSeekV4VisionEncoder.cpp,
so the C++ host tower and python/reference/deepseek4_vision.py see identical
tensors without a model file. Output: encoded rows (block order) and sentinels.

usage: make_vision_encoder_golden.py OUT.json
"""
import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "python"))
from reference.deepseek4_vision import DeepSeekV4Vision, PreparedImage, build_image_block  # noqa: E402

D, H, I, LAYERS, P, R, T = 16, 2, 24, 2, 14, 3, 32


def synth(seed: int, n: int, scale: float) -> torch.Tensor:
    i = torch.arange(n, dtype=torch.int64)
    v = (i * 2654435761 + seed * 97 + 12345) % 2001
    return (v.double() - 1000.0).float() / 1000.0 * scale


def shape_numel(shape):
    n = 1
    for s in shape:
        n *= s
    return n


def build():
    specs = {"v.patch_embd.weight": ([P, P, 3, D], 0.05), "v.patch_embd.bias": ([D], 0.1),
             "v.post_ln.weight": ([D], 0.5), "mm.1.weight": ([D * R * R, T], 0.08), "mm.1.bias": ([T], 0.1),
             "mm.2.weight": ([T, T], 0.15), "mm.2.bias": ([T], 0.1), "v.token_embd.img_start": ([T], 1.0),
             "v.token_embd.img_pad": ([T], 1.0), "v.image_newline": ([T], 1.0), "v.token_embd.img_end": ([T], 1.0)}
    for l in range(LAYERS):
        p = f"v.blk.{l}."
        specs.update({p + "ln1.weight": ([D], 0.5), p + "attn_qkv.weight": ([D, 3 * D], 0.2), p + "attn_qkv.bias": ([3 * D], 0.1),
                      p + "attn_out.weight": ([D, D], 0.2), p + "attn_out.bias": ([D], 0.1), p + "ln2.weight": ([D], 0.5),
                      p + "ffn_gate.weight": ([D, I], 0.2), p + "ffn_up.weight": ([D, I], 0.2), p + "ffn_down.weight": ([I, D], 0.2)})
    w = {}
    for seed, name in enumerate(sorted(specs)):
        shape, scale = specs[name]
        t = synth(seed, shape_numel(shape), scale)
        if name.endswith("ln1.weight") or name.endswith("ln2.weight") or name == "v.post_ln.weight":
            t = t + 1.0
        # torch layout: reversed ggml dims (outermost first)
        w[name] = t.view(*reversed(shape))
    return specs, w


def main():
    specs, w = build()
    vis = DeepSeekV4Vision.__new__(DeepSeekV4Vision)
    vis.w, vis.md = w, {}
    vis.n_layers, vis.dim, vis.heads, vis.patch, vis.merge, vis.min_pixels = LAYERS, D, H, P, R, 147456
    cases = []
    for vit_h, vit_w in [(5, 4), (3, 3), (7, 2), (1, 1)]:
        llm_h, llm_w = -(-vit_h // R), -(-vit_w // R)
        patches = synth(1000 + vit_h * 10 + vit_w, vit_h * vit_w * 3 * P * P, 1.0).view(vit_h * vit_w, -1)
        patches = patches.to(torch.bfloat16).float()
        img = PreparedImage(patches, vit_h, vit_w, llm_h, llm_w, None)
        with torch.no_grad():
            rows, block = vis.encode(img)
        cases.append({"vit_h": vit_h, "vit_w": vit_w, "rows": rows.flatten().tolist()})
    table = vis.sentinel_table()
    json.dump({"dim": D, "heads": H, "inter": I, "layers": LAYERS, "text_dim": T,
               "tensors": {k: v[0] for k, v in specs.items()}, "cases": cases,
               "sentinels": table.tolist()}, open(sys.argv[1], "w"))


if __name__ == "__main__":
    main()
