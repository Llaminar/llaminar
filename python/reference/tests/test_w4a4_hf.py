"""Device-free contracts for native W4A4 source ownership and the pinned HF graph.

Tiny, complete GGUF fixtures exercise the real streamed loader and HF module
replacement. They are construction/execution contracts, not real-model parity
or production-kernel certification. Recorded native arithmetic is tested in
test_w4a4.py; no expected model output is regenerated by this fixture writer.
"""

