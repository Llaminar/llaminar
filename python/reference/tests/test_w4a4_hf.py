def write_fixture(path: Path, metadata: dict, tensors: list[tuple], *, trailing: bytes = b'') -> None:
    """Write a small exact-extent GGUF; tensor shapes use standard (N,K) order."""
    def string(value):
        encoded = value.encode('utf-8')
        return struct.pack('<Q', len(encoded)) + encoded

    header = bytearray(b'GGUF' + struct.pack('<IQQ', 3, len(tensors), len(metadata)))
    for name, value in metadata.items():
        header.extend(string(name))
        if isinstance(value, str):
            header.extend(struct.pack('<I', 8) + string(value))
        elif isinstance(value, int):
            header.extend(struct.pack('<II', 4, value))
        elif isinstance(value, float):
            header.extend(struct.pack('<If', 6, value))
        else:
            raise ValueError('Fixture metadata must use explicit scalar types')
    data = bytearray()
    for name, shape, type_id, payload in tensors:
        data.extend(b'\0' * ((-len(data)) % 32))
        header.extend(string(name) + struct.pack('<I', len(shape)))
        for dimension in reversed(shape):
            header.extend(struct.pack('<Q', dimension))
        header.extend(struct.pack('<IQ', int(type_id), len(data)))
        data.extend(payload)
    header.extend(b'\0' * ((-len(header)) % 32))
    path.write_bytes(header + data + trailing)


class W4A4HFModuleContract(unittest.TestCase):
    """A native projection owns operands, not a disguised floating parameter."""

    def test_replacement_retires_float_parameter_and_preserves_outputs(self):
        model = torch.nn.Sequential(torch.nn.Linear(256, 3, bias=False))
        parameters = dict(model.named_parameters())
        loaded = set()
        weights = W4A4Weights.from_bytes(source_rows(patterned_codes(3, 256)), (3, 256), 44)
        values = torch.arange(512, dtype=torch.float32).reshape(2, 256) / 127
        install_native_linear(model, '0.weight', weights, parameters, loaded)
        self.assertIsInstance(model[0], W4A4Linear)
        self.assertEqual(parameters, {})
        self.assertEqual(list(model.parameters()), [])
        self.assertEqual(loaded, {'0.weight'})
        self.assertEqual(set(model.state_dict()), {'0.codes', '0.units', '0.multipliers'})
        self.assertEqual(model(values).numpy().tobytes(), weights.linear(values).numpy().tobytes())
        model.to('cpu').eval()
        with self.assertRaisesRegex(ValueError, 'CPU FP32 scale'):
            model.half()
        self.assertEqual(model[0].units.dtype, torch.float32)
        with torch.autocast('cpu', dtype=torch.bfloat16):
            with self.assertRaisesRegex(ValueError, 'without autocast'):
                model(values)
        with self.assertRaisesRegex(ValueError, 'duplicate'):
            install_native_linear(model, '0.weight', weights, parameters, loaded)

    def test_invalid_binding_is_rejected_before_replacement(self):
        weights = W4A4Weights.from_bytes(source_rows(patterned_codes(3, 256)), (3, 256), 44)
        for layer in [torch.nn.Linear(256, 3), torch.nn.Linear(256, 4, bias=False)]:
            model = torch.nn.Sequential(layer)
            with self.assertRaises(ValueError):
                install_native_linear(model, '0.weight', weights, dict(model.named_parameters()), set())
            self.assertIs(model[0], layer)


class W4A4NativeSourceContract(unittest.TestCase):
    """Native source extent, representation selection and mmap retirement stay exact."""

    def test_native_stream_retains_both_formats_without_float_matrices(self):
        for type_id in [44, 45]:
            with self.subTest(type_id=type_id), tempfile.TemporaryDirectory() as directory:
                path = Path(directory) / 'native.gguf'
                payload = source_rows(patterned_codes(3, 512), rotation=512)
                write_fixture(path, {'general.architecture': 'qwen35', 'ruquant.w4a4': 'fixture'},
                              [('blk.0.ffn_down.weight', (3, 512), type_id, payload)], trailing=b'\xa5' * 65536)
                loader = GGUFLoader(path)
                with self.assertRaisesRegex(ValueError, 'native operands'):
                    list(loader.iter_state_dict())
                with mock.patch('python.reference.loaders.gguf_loader.dequantize.dequantize',
                                side_effect=AssertionError('Native weights must not enter dequantization')):
                    pairs = list(loader.iter_state_dict(weight_mode=GGUFWeightMode.NATIVE_OPERANDS))
                self.assertEqual(len(pairs), 1)
                name, weights = pairs[0]
                self.assertEqual(name, 'model.layers.0.mlp.down_proj.weight')
                self.assertIsInstance(weights, W4A4Weights)
                self.assertEqual(weights.type_id, type_id)
                self.assertTrue(np.array_equal(weights.codes.numpy(), patterned_codes(3, 512)))
                # Closing the loader's mmap cannot invalidate the independently owned operands.
                self.assertTrue(torch.isfinite(weights.linear(torch.ones(1, 512))).all())

    def test_malformed_single_block_releases_source_view(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'malformed.gguf'
            payload = bytearray(source_rows(patterned_codes(1, 256)))
            struct.pack_into('<f', payload, 0, float('nan'))
            write_fixture(path, {'general.architecture': 'qwen35', 'ruquant.w4a4': 'fixture'},
                          [('blk.0.ffn_gate.weight', (1, 256), 44, payload)])
            with self.assertRaisesRegex(ValueError, 'finite and nonnegative'):
                list(GGUFLoader(path).iter_state_dict(weight_mode=GGUFWeightMode.NATIVE_OPERANDS))
            # A leaked mmap export would mask the validation failure with BufferError.

    def test_native_extent_requires_complete_rows(self):
        parser = GGUFParser.__new__(GGUFParser)
        for shape in [(2, 255), (1, 1, 256), (0, 256)]:
            with self.assertRaises(ValueError):
                parser._calculate_tensor_size(GGUFTensorInfo('weight', list(shape), GGUFTensorType.W4A4, 0))
        self.assertEqual(parser._calculate_tensor_size(GGUFTensorInfo('weight', [3, 512], GGUFTensorType.W4A4H, 0)), 864)

    def test_native_type_requires_explicit_export_contract(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'unadmitted.gguf'
            write_fixture(path, {'general.architecture': 'qwen35'},
                          [('blk.0.ffn_gate.weight', (1, 256), 44, source_rows(patterned_codes(1, 256)))])
            with self.assertRaisesRegex(ValueError, 'ruquant contract'):
                list(GGUFLoader(path).iter_state_dict(weight_mode=GGUFWeightMode.NATIVE_OPERANDS))


class W4A4HFGraphContract(unittest.TestCase):
    """Exercise native projections through the pinned HF recurrent/attention graph."""

    def test_streamed_hybrid_graph_and_cache_reset(self):
        from python.reference.loaders.tensor_name_mapper import (
            QWEN35_FULL_ATTN_MAP, QWEN35_LINEAR_ATTN_MAP, QWEN35_SHARED_MAP,
        )
        from python.reference.qwen35 import Qwen35ReferenceModel
        from transformers.models.qwen3_5.modeling_qwen3_5 import Qwen3_5ForCausalLM

        provenance = require_pinned_hf_runtime()
        metadata = {
            'general.architecture': 'qwen35', 'ruquant.w4a4': 'device-free contract fixture',
            'qwen35.block_count': 2, 'qwen35.embedding_length': 256,
            'qwen35.feed_forward_length': 512, 'qwen35.vocab_size': 64,
            'qwen35.context_length': 32, 'qwen35.attention.head_count': 4,
            'qwen35.attention.head_count_kv': 2, 'qwen35.attention.key_length': 64,
            'qwen35.ssm.state_size': 64, 'qwen35.ssm.group_count': 2,
            'qwen35.ssm.time_step_rank': 4, 'qwen35.ssm.inner_size': 256,
            'qwen35.ssm.conv_kernel': 4, 'qwen35.full_attention_interval': 2,
        }
        parser = GGUFParser.__new__(GGUFParser)
        parser.metadata, parser.tensors = metadata, []
        config = Qwen35ReferenceModel._build_hf_config(parser.get_config_dict())
        with torch.random.fork_rng(devices=[]):
            torch.manual_seed(411)
            expected = Qwen3_5ForCausalLM(config).eval()
        reverse_names = {}
        for mapping in [QWEN35_SHARED_MAP, QWEN35_LINEAR_ATTN_MAP, QWEN35_FULL_ATTN_MAP]:
            for native, hf in mapping.items():
                for layer in range(2):
                    reverse_names[hf.format(layer)] = native.format(layer)
        tensors = []
        native_weights = {}
        parameters = dict(expected.named_parameters())
        for name, parameter in parameters.items():
            source_name = reverse_names[name]
            values = parameter.detach().clone()
            is_native = ('.mlp.' in name or '.self_attn.' in name and name.endswith('_proj.weight')
                         or name.endswith(('in_proj_qkv.weight', 'in_proj_z.weight')))
            if is_native:
                rows, width = values.shape
                type_id = 45 if name.endswith(('down_proj.weight', 'o_proj.weight')) else 44
                payload = source_rows(patterned_codes(rows, width), unit=0.00390625, rotation=width)
                native_weights[name] = W4A4Weights.from_bytes(payload, tuple(values.shape), type_id)
                tensors.append((source_name, tuple(values.shape), type_id, payload))
                continue
            if name.endswith('norm.weight') and 'linear_attn.norm' not in name:
                values += 1
            if name.endswith('.A_log'):
                values = -torch.exp(values)
                with torch.no_grad():
                    parameter.copy_(torch.log(-values))
            if name.endswith('conv1d.weight'):
                values = values.squeeze(1)
            tensors.append((source_name, tuple(values.shape), 0, values.numpy().tobytes()))
        loaded = set()
        for name, weights in native_weights.items():
            install_native_linear(expected, name, weights, parameters, loaded)

        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / 'tiny-native.gguf'
            write_fixture(path, metadata, tensors)
            actual = Qwen35ReferenceModel('qwen35', path, device='cpu')
            with mock.patch.object(actual, '_resolve_tokenizer'):
                actual.load_model(torch_dtype=torch.float32)
            self.assertEqual(actual._w4a4_reference_policy, provenance)
            self.assertEqual(sum(isinstance(module, W4A4Linear) for module in actual.hf_model.modules()), len(native_weights))
            for name in native_weights:
                self.assertNotIn(name, dict(actual.hf_model.named_parameters()))
            with torch.no_grad():
                for _ in range(2):
                    prompt = torch.tensor([[2, 3, 5]])
                    expected_prefill = expected(prompt, use_cache=True)
                    actual_prefill = actual.forward(prompt, use_cache=True)
                    self.assertEqual(actual_prefill['logits'].tobytes(), expected_prefill.logits.numpy().tobytes())
                    next_token = torch.tensor([[7]])
                    expected_decode = expected(next_token, past_key_values=expected_prefill.past_key_values, use_cache=True)
                    actual_decode = actual.forward(next_token, past_key_values=actual_prefill['past_key_values'], use_cache=True)
                    self.assertEqual(actual_decode['logits'].tobytes(), expected_decode.logits.numpy().tobytes())
            with self.assertRaisesRegex(RuntimeError, 'basis compatibility'):
                actual.generate_mtp_sidecar_decode_snapshots('unused', 1, directory)

    def test_unpinned_runtime_is_not_admitted(self):
        with mock.patch('python.reference.quantization.w4a4.TRANSFORMERS_REVISION', '0' * 40):
            with self.assertRaisesRegex(RuntimeError, 'pinned torch and Transformers'):
                require_pinned_hf_runtime()


