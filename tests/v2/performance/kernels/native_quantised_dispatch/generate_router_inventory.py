"""Embed validated router geometry without a test-runner source-tree dependency.

GTest expands parameter generators even when a different test is selected. Read
the canonical GGUF/release manifests during the build, so installed runners can
enumerate and execute unrelated tests without reopening those source documents.
The common loader remains the sole geometry and manifest-validation authority.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .qwen_moe_gguf_patterns import qwen_moe_prefill_mixtures


def render_router_inventory() -> str:
    """Return a deterministic C++ geometry array from the validated mixtures."""
    shapes = sorted({(m.hidden_size, m.expert_count) for m in qwen_moe_prefill_mixtures()})
    if not shapes:
        raise ValueError("The validated MoE inventory contains no router geometry")
    entries = "\n".join(f"    std::pair{{{width}, {experts}}}," for width, experts in shapes)
    return f"""/**
 * @file ROCmRouterModelInventoryGenerated.h
 * @brief Build-owned router geometry from the validated canonical GGUF inventory.
 *
 * Generated by generate_router_inventory.py; never edit by hand. Parameter
 * registration borrows this embedded inventory without opening source files.
 */
#pragma once
#include <array>
#include <utility>
namespace llaminar2::test
{{
inline constexpr std::array<std::pair<int, int>, {len(shapes)}> kRouterModelGeometries{{{{
{entries}
}}}};
}}
"""


def main() -> None:
    """Write the requested header only after complete manifest validation."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    content = render_router_inventory()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
