"""Build a bounded, provenance-pinned inventory of production MoE GGUFs.

The ordinary and grouped-prefill trainers need to benchmark the codebook
mixtures that users actually download.  Quantization names such as
``UD-IQ3_S`` are not sufficient evidence: a mixed quant may use one format for
routed gate/up tensors, another for routed down tensors, and a third for the
shared expert, with exceptional layers using still another format.

This module reads that evidence directly from GGUF tensor descriptors hosted
on Hugging Face.  It deliberately does *not* download model payloads.  Each
HTTP request is bounded to an adaptive prefix of a pinned LFS object, metadata
arrays are skipped without materialization, and only the small tensor-info
table is retained.  Split GGUF shards are merged by tensor name before the
per-layer MoE signatures are validated and deduplicated.

The checked-in manifest generated by this module is a reviewed input to every
backend's prefill matrix.  Network access is therefore a refresh-time concern;
unit tests use synthetic in-memory GGUF headers and never contact Hugging Face.
"""

