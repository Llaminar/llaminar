/**
 * @file DeepSeekV4ChatEncoding.h
 * @brief Native DeepSeek-V4 prompt encoder (official encoding, vLLM request mapping).
 *
 * DeepSeek-V4 ships no Jinja chat template; its format is defined by the
 * Python reference encoder (encoding/encoding_dsv4.py in the checkpoint and
 * vllm/tokenizers/deepseek_v4_encoding.py in vLLM). This file is a faithful
 * C++ port of the production vLLM encoder so Llaminar renders byte-identical
 * prompts for identical OpenAI requests:
 *  - BOS, then (thinking mode only) the reasoning-effort preamble;
 *  - the system message, followed by request tools rendered in the DSML
 *    "## Tools" section;
 *  - user turns as "<｜User｜>", with tool results merged into the following
 *    user turn as <tool_result> blocks ordered by the preceding call order;
 *  - assistant turns as reasoning + "</think>" (kept only after the last user
 *    turn unless tools are present), content, a DSML tool_calls block and EOS;
 *  - "<｜Assistant｜><think>" (thinking) or "<｜Assistant｜></think>" (chat) as
 *    the generation prompt.
 * Tool schemas and non-string arguments use Python json.dumps spelling
 * (PythonJson.h). Images, quick-instruction "task" tokens and
 * continue_final_message are not part of Llaminar's request surface and are
 * rejected or absent by construction.
 *
 * Golden prompts: tests/v2/unit/utils/fixtures/deepseek_v4_chat_encoding_golden.json,
 * generated by scripts/deepseek4/make_chat_encoding_golden.py from the production
 * vLLM encoder.
 */
#pragma once

#include <nlohmann/json.hpp>
#include <optional>
#include <string>

namespace llaminar2::deepseek4
{
    /** @brief Rendering mode of the generation prompt and of retained reasoning. */
    enum class ChatThinkingMode
    {
        Chat,     ///< "<｜Assistant｜></think>": answer directly.
        Thinking, ///< "<｜Assistant｜><think>": reason first.
    };

    /** @brief Reasoning-effort preamble selected in thinking mode. */
    enum class ChatReasoningEffort
    {
        Low,  ///< No preamble (the encoder's default).
        High, ///< "Reasoning Effort: Absolute maximum ..." preamble.
        Max,  ///< "Reasoning Effort: Beyond maximum ..." preamble.
    };

    /** @brief Resolved per-request prompt policy. */
    struct ChatPromptPolicy
    {
        ChatThinkingMode thinking = ChatThinkingMode::Thinking;
        ChatReasoningEffort effort = ChatReasoningEffort::High;
    };

    /**
     * @brief Resolve the OpenAI request controls exactly as vLLM's DeepSeek-V4 tokenizer does.
     * @param thinking_enabled Request thinking switch after model defaults
     *        (thinking defaults on for DeepSeek-V4).
     * @param reasoning_effort Validated client value, if any: "none" forces chat
     *        mode; "max" selects Max; "low"/"minimal"/"medium" select Low; any
     *        other value ("high", "xhigh") selects High. Absent: High when
     *        thinking, otherwise irrelevant.
     * @return Immutable prompt policy.
     */
    ChatPromptPolicy resolveChatPromptPolicy(bool thinking_enabled,
                                             const std::optional<std::string> &reasoning_effort);

    /**
     * @brief Attach request tools to the first system message, inserting an empty one first if none exists.
     * @param messages OpenAI message array, modified in place.
     * @param tools Non-empty OpenAI tool array ({"type":"function","function":{...}}).
     */
    void attachRequestTools(nlohmann::ordered_json &messages, const nlohmann::ordered_json &tools);

    /**
     * @brief Encode an OpenAI-format conversation into the DeepSeek-V4 prompt text.
     * @param messages Order-preserving array of messages with "role", optional
     *        "content" (string, null or an array of {"type":"text"} parts),
     *        "reasoning", "tool_calls" (OpenAI objects whose arguments are a JSON
     *        string or object), "tool_call_id", and "tools" (system/developer).
     * @param policy Resolved thinking mode and effort.
     * @param add_generation_prompt Append the assistant generation prompt.
     * @return Prompt text, beginning with the BOS token string.
     * @throws std::invalid_argument For roles, content parts or tool arguments the
     *         reference encoder rejects.
     */
    std::string encodeChatMessages(const nlohmann::ordered_json &messages, ChatPromptPolicy policy,
                                   bool add_generation_prompt = true);

    /// Special-token spellings shared with the output parser.
    inline constexpr const char *kBosToken = "<｜begin▁of▁sentence｜>";
    inline constexpr const char *kEosToken = "<｜end▁of▁sentence｜>";
    inline constexpr const char *kThinkStart = "<think>";
    inline constexpr const char *kThinkEnd = "</think>";
    inline constexpr const char *kDsmlToken = "｜DSML｜";
} // namespace llaminar2::deepseek4
