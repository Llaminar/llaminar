/**
 * @file CPUNativeNEONExactOverlay.h
 * @brief Total native ARM projection schedule plus authenticated exact overlays.
 *
 * Native NEON projections reduce every row over full K in fixed register trees,
 * so the only schedule dimensions are numerically neutral:
 *
 * - the shared-row tile (two or four physical rows reuse each decoded weight
 *   chunk), and
 * - the number of adjacent 64-column chunks one dynamically claimed task owns.
 *
 * Neither changes a single output byte. The *total* policy (four-row tiles,
 * one chunk per task) is defined for every positive M/N/K/worker geometry.
 * Exact overlays replace it only for measured keys: one prepared execution
 * codebook and source block shape, the serial-equivalent policy N, K, the
 * physical M and the invocation worker count. They are generated by
 * `native_vnni_dispatch/neon_exact_overlay.py` from authenticated GB10/ARM
 * candidate sweeps (`Perf__CPUNativeNEONExactOverlay`), never by generic
 * fitting, and an unseen key always falls back to the total policy rather
 * than to a "nearby" entry.
 */
#pragma once

#include "CPUNativeNEONProjectionBatch.h"

#include <algorithm>
#include <array>
#include <cstdint>
#include <span>
#include <stdexcept>
#include <tuple>

namespace llaminar2::cpu::native_vnni
{
    /** @brief One measured exact key and the physical schedule that won it. */
    struct NativeNEONExactOverlayEntry
    {
        std::uint8_t codebook_id = 0; ///< Prepared execution codebook.
        bool is_superblock = false;   ///< Source 256-value superblock layout.
        int n = 0;                    ///< Serial-equivalent policy output width.
        int k = 0;                    ///< Logical reduction width.
        int m = 0;                    ///< Physical row count of the invocation.
        int workers = 0;              ///< Invocation worker budget.
        NEONProjectionRowTile tile = NEONProjectionRowTile::Four; ///< Winning row reuse.
        int n_block_chunks = 1;       ///< Winning adjacent 64-column chunks per task.

        /** @return Strict key order used by the sorted generated table. */
        constexpr auto key() const noexcept
        {
            return std::tuple{codebook_id, is_superblock, n, k, m, workers};
        }
    };

    /** @brief Resolved schedule and whether an exact overlay supplied it. */
    struct NativeNEONSchedule
    {
        NEONProjectionRowTile tile = NEONProjectionRowTile::Four; ///< Shared-row tile.
        int n_block_chunks = 1;                                   ///< Chunks per task.
        bool exact = false;                                       ///< True only for a measured key.
    };

    namespace neon_overlay_detail
    {
        /** @brief Installed generated table (sorted by key, unique). */
#include "CPUNativeNEONExactOverlayGenerated.inc"

        /** @return Whether one entry carries a physically valid schedule. */
        constexpr bool validEntry(const NativeNEONExactOverlayEntry &entry) noexcept
        {
            return entry.n > 0 && entry.k > 0 && entry.m > 0 && entry.workers > 0 &&
                (entry.n_block_chunks == 1 || entry.n_block_chunks == 2 ||
                 entry.n_block_chunks == 4 || entry.n_block_chunks == 8);
        }

        /** @return Whether a table is valid, strictly sorted and therefore unique. */
        constexpr bool validTable(std::span<const NativeNEONExactOverlayEntry> table) noexcept
        {
            for (std::size_t index = 0; index < table.size(); ++index)
            {
                if (!validEntry(table[index]))
                    return false;
                if (index && !(table[index - 1].key() < table[index].key()))
                    return false;
            }
            return true;
        }
        static_assert(validTable(kGeneratedNativeNEONExactOverlay),
            "Generated native NEON exact overlays must be valid, sorted and unique");
    }

    /** @return The installed, compile-time validated exact overlay table. */
    inline std::span<const NativeNEONExactOverlayEntry> installedNativeNEONExactOverlay() noexcept
    {
        return neon_overlay_detail::kGeneratedNativeNEONExactOverlay;
    }

    /**
     * @brief Resolve the automatic schedule for one native projection invocation.
     * @param codebook_id Prepared execution codebook of the weights.
     * @param is_superblock Source superblock layout of the weights.
     * @param policy_n Serial-equivalent policy output width.
     * @param k Logical reduction width.
     * @param m Physical row count.
     * @param workers Invocation worker budget.
     * @param table Sorted exact table; the installed table by default.
     * @return The exact entry's schedule for a measured key, otherwise the total
     *         four-row/one-chunk policy. Never interpolates between keys.
     * @throws std::invalid_argument For non-positive geometry or an invalid table.
     */
    inline NativeNEONSchedule resolveNativeNEONSchedule(std::uint8_t codebook_id, bool is_superblock,
        int policy_n, int k, int m, int workers,
        std::span<const NativeNEONExactOverlayEntry> table = installedNativeNEONExactOverlay())
    {
        if (policy_n <= 0 || k <= 0 || m <= 0 || workers <= 0)
            throw std::invalid_argument("Native ARM schedule requires positive N/K/M/workers");
        if (!neon_overlay_detail::validTable(table))
            throw std::invalid_argument("Native ARM exact overlay table is unsorted, duplicated or invalid");
        const auto key = std::tuple{codebook_id, is_superblock, policy_n, k, m, workers};
        const auto found = std::lower_bound(table.begin(), table.end(), key,
            [](const NativeNEONExactOverlayEntry &entry, const auto &value) { return entry.key() < value; });
        if (found != table.end() && found->key() == key)
            return {found->tile, found->n_block_chunks, true};
        return {};
    }
} // namespace llaminar2::cpu::native_vnni
